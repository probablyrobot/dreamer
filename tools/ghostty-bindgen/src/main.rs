//! Generate Rust bindings for the pinned `libghostty-vt` headers.
//!
//! Invoked by `cargo xtask bindings [--check]`, which supplies the header
//! paths of the prepared release. With `--check`, fails if the checked-in
//! bindings differ from what the headers produce.

use std::path::PathBuf;
use std::process::ExitCode;

fn main() -> ExitCode {
    let mut include = None;
    let mut out = None;
    let mut check = false;
    let mut args = std::env::args().skip(1);
    while let Some(arg) = args.next() {
        match arg.as_str() {
            "--include" => include = args.next().map(PathBuf::from),
            "--out" => out = args.next().map(PathBuf::from),
            "--check" => check = true,
            other => {
                eprintln!("unknown argument `{other}`");
                return ExitCode::FAILURE;
            }
        }
    }
    let (Some(include), Some(out)) = (include, out) else {
        eprintln!("usage: ghostty-bindgen --include <dir> --out <file> [--check]");
        return ExitCode::FAILURE;
    };

    let header = include.join("ghostty").join("vt.h");
    let bindings = match bindgen::Builder::default()
        .header(header.to_string_lossy())
        .clang_arg(format!("-I{}", include.display()))
        .clang_arg("-DGHOSTTY_STATIC")
        .allowlist_function("ghostty_.*")
        .allowlist_type("Ghostty.*")
        .allowlist_var("GHOSTTY_.*")
        // Defined through <limits.h> (INT_MAX); clang only evaluates it with
        // some platform headers, so it is excluded to keep output identical
        // on every host. It is an enum sentinel with no use from Rust.
        .blocklist_item("GHOSTTY_ENUM_MAX_VALUE")
        // Every exported enum is a C `int`-sized enum with sentinel max values;
        // constified modules keep unknown values from future minor releases
        // representable instead of being undefined behavior.
        .default_enum_style(bindgen::EnumVariation::ModuleConsts)
        .prepend_enum_name(false)
        .layout_tests(true)
        .derive_default(true)
        .generate_comments(false)
        .formatter(bindgen::Formatter::Rustfmt)
        .generate()
    {
        Ok(b) => b,
        Err(e) => {
            eprintln!("bindgen failed: {e}");
            return ExitCode::FAILURE;
        }
    };
    let generated = format!(
        "// @generated by tools/ghostty-bindgen from the pinned libghostty-vt headers.\n\
         // Do not edit. Regenerate with `cargo xtask bindings`.\n\n{bindings}"
    );

    if check {
        let current = std::fs::read_to_string(&out).unwrap_or_default();
        if current != generated {
            eprintln!(
                "{} is out of date with the pinned headers; run `cargo xtask bindings`",
                out.display()
            );
            print_diff(&current, &generated);
            return ExitCode::FAILURE;
        }
        println!("bindings: up to date");
    } else if let Err(e) = std::fs::write(&out, generated) {
        eprintln!("cannot write {}: {e}", out.display());
        return ExitCode::FAILURE;
    } else {
        println!("bindings: wrote {}", out.display());
    }
    ExitCode::SUCCESS
}

/// Show where the checked-in and generated bindings diverge.
fn print_diff(current: &str, generated: &str) {
    let fresh = std::env::temp_dir().join("ghostty-bindings.generated.rs");
    if std::fs::write(&fresh, generated).is_ok() {
        let _ = std::process::Command::new("diff")
            .arg("-u")
            .arg("--label")
            .arg("checked-in")
            .arg("--label")
            .arg("generated")
            .arg("-")
            .arg(&fresh)
            .stdin(std::process::Stdio::piped())
            .spawn()
            .and_then(|mut child| {
                use std::io::Write as _;
                if let Some(mut stdin) = child.stdin.take() {
                    stdin.write_all(current.as_bytes())?;
                }
                child.wait()
            });
    }
}
