//! The JSON-RPC (OpenRPC), Protobuf, and Luau renderings of the schema.

use std::fmt::Write as _;

use serde_json::{Map, Value, json};

use crate::schema::{Field, Kind, Schema, TypeDef};

// ---- OpenRPC ---------------------------------------------------------------

pub fn openrpc(s: &Schema) -> String {
    let mut schemas = Map::new();
    for (name, t) in s.enums() {
        let names: Vec<&str> = t.values.iter().map(|v| v.name.as_str()).collect();
        let mut e = json!({ "type": "string", "enum": names });
        describe(&mut e, t.doc.as_deref());
        schemas.insert(name.to_owned(), e);
    }
    for (name, t) in s.messages() {
        schemas.insert(name.to_owned(), message_schema(s, t));
    }
    let methods: Vec<Value> = s
        .methods
        .iter()
        .map(|m| {
            let params: Vec<Value> = s
                .messages()
                .find(|(n, _)| *n == m.params)
                .map(|(_, t)| {
                    let mut p: Vec<Value> = t
                        .fields
                        .iter()
                        .map(|f| {
                            let mut d = json!({ "name": f.name, "schema": field_schema(s, f) });
                            describe(&mut d, f.doc.as_deref());
                            d
                        })
                        .collect();
                    if let Some(of) = &t.oneof {
                        p.push(json!({ "name": of.name, "schema": oneof_schema(t) }));
                    }
                    p
                })
                .unwrap_or_default();
            let mut v = json!({
                "name": m.method,
                "paramStructure": "by-name",
                "params": params,
                "result": { "name": "result", "schema": { "$ref": format!("#/components/schemas/{}", m.result) } },
                "x-mutation": m.mutation,
            });
            if let Some(d) = &m.doc {
                v["summary"] = json!(d);
            }
            v
        })
        .collect();
    let doc = json!({
        "openrpc": "1.3.2",
        "info": {
            "title": "Dreamer API",
            "version": format!("{}.{}", s.version.major, s.version.minor),
            "description": format!(
                "Generated by tools/api-gen from crates/api/schema/api.yaml. Do not edit. \
                 Package {}. Errors are JSON-RPC 2.0 error objects (RpcError).",
                s.package
            ),
        },
        "methods": methods,
        "components": { "schemas": schemas },
    });
    let mut out = serde_json::to_string_pretty(&doc).unwrap_or_default();
    out.push('\n');
    out
}

fn describe(v: &mut Value, doc: Option<&str>) {
    if let Some(d) = doc {
        v["description"] = json!(d);
    }
}

fn scalar_schema(ty: &str) -> Value {
    match ty {
        "string" => json!({ "type": "string" }),
        "bool" => json!({ "type": "boolean" }),
        "u32" | "u64" => json!({ "type": "integer", "minimum": 0 }),
        "i32" | "i64" => json!({ "type": "integer" }),
        _ => json!({ "type": "string", "contentEncoding": "base64" }),
    }
}

fn field_schema(s: &Schema, f: &Field) -> Value {
    let one = match s.kind(&f.ty) {
        Some(Kind::Scalar) | None => scalar_schema(&f.ty),
        _ => json!({ "$ref": format!("#/components/schemas/{}", f.ty) }),
    };
    if f.repeated {
        json!({ "type": "array", "items": one })
    } else {
        one
    }
}

fn oneof_schema(t: &TypeDef) -> Value {
    let mut props = Map::new();
    if let Some(of) = &t.oneof {
        for v in &of.variants {
            props.insert(
                v.name.clone(),
                json!({ "$ref": format!("#/components/schemas/{}", v.ty) }),
            );
        }
    }
    json!({ "type": "object", "minProperties": 1, "maxProperties": 1, "properties": props })
}

fn message_schema(s: &Schema, t: &TypeDef) -> Value {
    let mut props = Map::new();
    for f in &t.fields {
        let mut fs = field_schema(s, f);
        describe(&mut fs, f.doc.as_deref());
        props.insert(f.name.clone(), fs);
    }
    if let Some(of) = &t.oneof {
        props.insert(of.name.clone(), oneof_schema(t));
    }
    let mut v = json!({ "type": "object", "properties": props });
    describe(&mut v, t.doc.as_deref());
    v
}

// ---- Protobuf --------------------------------------------------------------

pub fn proto(s: &Schema) -> String {
    let mut o = String::new();
    let _ = writeln!(
        o,
        "// @generated by tools/api-gen from crates/api/schema/api.yaml. Do not edit.\n\
         // Dreamer API {}.{}. Records only: the transport is Dreamer's own framed\n\
         // protocol (docs/api.md), not gRPC. JSON-RPC uses snake_case enum names\n\
         // (for example \"live\"), not the Protobuf JSON mapping.\n\n\
         syntax = \"proto3\";\n\npackage {};\n",
        s.version.major, s.version.minor, s.package
    );
    for (name, t) in s.enums() {
        comment(&mut o, "", t.doc.as_deref());
        let _ = writeln!(o, "enum {name} {{");
        let prefix = crate::schema::snake(name).to_ascii_uppercase();
        for v in &t.values {
            comment(&mut o, "  ", v.doc.as_deref());
            let _ = writeln!(o, "  {prefix}_{} = {};", v.name.to_ascii_uppercase(), v.n);
        }
        o.push_str("}\n\n");
    }
    for (name, t) in s.messages() {
        comment(&mut o, "", t.doc.as_deref());
        let _ = writeln!(o, "message {name} {{");
        if !t.reserved.is_empty() {
            let r: Vec<String> = t.reserved.iter().map(u32::to_string).collect();
            let _ = writeln!(o, "  reserved {};", r.join(", "));
        }
        for f in &t.fields {
            comment(&mut o, "  ", f.doc.as_deref());
            let ty = match f.ty.as_str() {
                "u32" => "uint32",
                "u64" => "uint64",
                "i32" => "int32",
                "i64" => "int64",
                other => other,
            };
            let card = if f.repeated {
                "repeated "
            } else if f.optional {
                "optional "
            } else {
                ""
            };
            let _ = writeln!(o, "  {card}{ty} {} = {};", f.name, f.n);
        }
        if let Some(of) = &t.oneof {
            let _ = writeln!(o, "  oneof {} {{", of.name);
            for v in &of.variants {
                let _ = writeln!(o, "    {} {} = {};", v.ty, v.name, v.n);
            }
            o.push_str("  }\n");
        }
        o.push_str("}\n\n");
    }
    o.push_str("// Methods (request record -> response record):\n");
    for m in &s.methods {
        let _ = writeln!(
            o,
            "//   {} ({} -> {}){}",
            m.method,
            m.params,
            m.result,
            if m.mutation { " mutation" } else { "" }
        );
    }
    o
}

fn comment(o: &mut String, indent: &str, doc: Option<&str>) {
    if let Some(d) = doc {
        for line in d.lines() {
            let _ = writeln!(o, "{indent}// {line}");
        }
    }
}

// ---- Luau ------------------------------------------------------------------

pub fn luau(s: &Schema) -> String {
    let mut o = String::new();
    let _ = writeln!(
        o,
        "--!strict\n\
         -- @generated by tools/api-gen from crates/api/schema/api.yaml. Do not edit.\n\
         -- Dreamer API {}.{} ({}). The host passes `call`, which performs one\n\
         -- method under the script's grants; bytes travel as base64 strings.\n",
        s.version.major, s.version.minor, s.package
    );
    for (name, t) in s.enums() {
        let names: Vec<String> = t.values.iter().map(|v| format!("\"{}\"", v.name)).collect();
        let _ = writeln!(o, "export type {name} = {}", names.join(" | "));
    }
    o.push('\n');
    for (name, t) in s.messages() {
        luau_comment(&mut o, "", t.doc.as_deref());
        if t.fields.is_empty() && t.oneof.is_none() {
            let _ = writeln!(o, "export type {name} = {{}}\n");
            continue;
        }
        let _ = writeln!(o, "export type {name} = {{");
        for f in &t.fields {
            let base = match f.ty.as_str() {
                "string" | "bytes" => "string".to_owned(),
                "bool" => "boolean".to_owned(),
                "u32" | "u64" | "i32" | "i64" => "number".to_owned(),
                other => other.to_owned(),
            };
            let ty = if f.repeated {
                format!("{{{base}}}?")
            } else {
                // Every field may be absent on the wire and takes its default.
                format!("{base}?")
            };
            let _ = writeln!(o, "\t{}: {ty},", f.name);
        }
        if let Some(of) = &t.oneof {
            let _ = writeln!(o, "\t{}: {{", of.name);
            for v in &of.variants {
                let _ = writeln!(o, "\t\t{}: {}?,", v.name, v.ty);
            }
            o.push_str("\t}?,\n");
        }
        o.push_str("}\n\n");
    }
    o.push_str("export type Call = (method: string, params: any) -> any\n\nreturn function(call: Call)\n\tlocal dreamer = {}\n");
    let mut services: Vec<&str> = Vec::new();
    for m in &s.methods {
        let service = m.method.split('.').next().unwrap_or_default();
        if !services.contains(&service) {
            services.push(service);
            let _ = writeln!(o, "\tdreamer.{service} = {{}}");
        }
    }
    for m in &s.methods {
        luau_comment(&mut o, "\t", m.doc.as_deref());
        let _ = writeln!(
            o,
            "\tfunction dreamer.{}(params: {}?): {}\n\t\treturn call(\"{}\", params or {{}})\n\tend",
            m.method, m.params, m.result, m.method
        );
    }
    for service in &services {
        let _ = writeln!(o, "\ttable.freeze(dreamer.{service})");
    }
    o.push_str("\treturn table.freeze(dreamer)\nend\n");
    o
}

fn luau_comment(o: &mut String, indent: &str, doc: Option<&str>) {
    if let Some(d) = doc {
        for line in d.lines() {
            let _ = writeln!(o, "{indent}--- {line}");
        }
    }
}
