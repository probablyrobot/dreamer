//! The compatibility lock: the accepted contract, one fact per line, and
//! the rules that compare a schema against it.

use std::collections::BTreeMap;

use crate::schema::{Schema, Version};

/// Everything a peer may depend on.
#[derive(Debug, Default, PartialEq, Eq)]
pub struct Contract {
    pub version: Option<Version>,
    /// message -> number -> "field name type card" or "variant name type"
    pub messages: BTreeMap<String, BTreeMap<u32, String>>,
    /// enum -> number -> name
    pub enums: BTreeMap<String, BTreeMap<i32, String>>,
    /// method -> "params -> result kind"
    pub methods: BTreeMap<String, String>,
    /// topic -> payload type
    pub notifications: BTreeMap<String, String>,
}

impl Contract {
    pub fn of(s: &Schema) -> Contract {
        let mut c = Contract {
            version: Some(s.version),
            ..Contract::default()
        };
        for (name, t) in s.messages() {
            let mut fields = BTreeMap::new();
            for f in &t.fields {
                let card = if f.repeated {
                    "repeated"
                } else if f.optional {
                    "optional"
                } else {
                    "single"
                };
                fields.insert(f.n, format!("field {} {} {card}", f.name, f.ty));
            }
            if let Some(of) = &t.oneof {
                for v in &of.variants {
                    fields.insert(v.n, format!("variant {}.{} {}", of.name, v.name, v.ty));
                }
            }
            c.messages.insert(name.to_owned(), fields);
        }
        for (name, t) in s.enums() {
            c.enums.insert(
                name.to_owned(),
                t.values.iter().map(|v| (v.n, v.name.clone())).collect(),
            );
        }
        for m in &s.methods {
            c.methods.insert(
                m.method.clone(),
                format!(
                    "{} -> {} {}",
                    m.params,
                    m.result,
                    if m.mutation { "mutation" } else { "query" }
                ),
            );
        }
        for n in &s.notifications {
            c.notifications.insert(n.topic.clone(), n.payload.clone());
        }
        c
    }

    pub fn render(&self) -> String {
        let mut o = String::from(
            "# Accepted API contract. Generated by `cargo xtask api`; do not edit.\n\
             # A change that removes or alters a line below breaks peers of the same\n\
             # major version and is refused unless the major version is bumped.\n",
        );
        if let Some(v) = self.version {
            o.push_str(&format!("version {} {}\n", v.major, v.minor));
        }
        for (name, fields) in &self.messages {
            o.push_str(&format!("message {name}\n"));
            for (n, f) in fields {
                o.push_str(&format!("  {n} {f}\n"));
            }
        }
        for (name, values) in &self.enums {
            o.push_str(&format!("enum {name}\n"));
            for (n, v) in values {
                o.push_str(&format!("  {n} {v}\n"));
            }
        }
        for (name, m) in &self.methods {
            o.push_str(&format!("method {name} {m}\n"));
        }
        for (topic, payload) in &self.notifications {
            o.push_str(&format!("notification {topic} {payload}\n"));
        }
        o
    }

    pub fn parse(text: &str) -> Result<Contract, String> {
        let mut c = Contract::default();
        enum Cur {
            None,
            Message(String),
            Enum(String),
        }
        let mut cur = Cur::None;
        for (i, line) in text.lines().enumerate() {
            let bad = || format!("compat.lock line {}: `{line}`", i + 1);
            if line.starts_with('#') || line.trim().is_empty() {
                continue;
            }
            if let Some(rest) = line.strip_prefix("  ") {
                let (n, body) = rest.split_once(' ').ok_or_else(bad)?;
                match &cur {
                    Cur::Message(m) => {
                        let n: u32 = n.parse().map_err(|_| bad())?;
                        c.messages
                            .entry(m.clone())
                            .or_default()
                            .insert(n, body.to_owned());
                    }
                    Cur::Enum(e) => {
                        let n: i32 = n.parse().map_err(|_| bad())?;
                        c.enums
                            .entry(e.clone())
                            .or_default()
                            .insert(n, body.to_owned());
                    }
                    Cur::None => return Err(bad()),
                }
                continue;
            }
            let (kw, rest) = line.split_once(' ').ok_or_else(bad)?;
            match kw {
                "version" => {
                    let (a, b) = rest.split_once(' ').ok_or_else(bad)?;
                    c.version = Some(Version {
                        major: a.parse().map_err(|_| bad())?,
                        minor: b.parse().map_err(|_| bad())?,
                    });
                }
                "message" => {
                    c.messages.entry(rest.to_owned()).or_default();
                    cur = Cur::Message(rest.to_owned());
                }
                "enum" => {
                    c.enums.entry(rest.to_owned()).or_default();
                    cur = Cur::Enum(rest.to_owned());
                }
                "method" => {
                    let (name, m) = rest.split_once(' ').ok_or_else(bad)?;
                    c.methods.insert(name.to_owned(), m.to_owned());
                    cur = Cur::None;
                }
                "notification" => {
                    let (topic, payload) = rest.split_once(' ').ok_or_else(bad)?;
                    c.notifications.insert(topic.to_owned(), payload.to_owned());
                    cur = Cur::None;
                }
                _ => return Err(bad()),
            }
        }
        Ok(c)
    }
}

#[derive(Debug, Default)]
pub struct Diff {
    pub breaking: Vec<String>,
    pub additive: Vec<String>,
}

pub fn diff(old: &Contract, new: &Contract) -> Diff {
    let mut d = Diff::default();
    for (name, fields) in &old.messages {
        let Some(now) = new.messages.get(name) else {
            d.breaking.push(format!("message {name} removed"));
            continue;
        };
        for (n, f) in fields {
            match now.get(n) {
                None => d.breaking.push(format!("{name}: field {n} ({f}) removed")),
                Some(g) if g != f => d
                    .breaking
                    .push(format!("{name}: field {n} changed from `{f}` to `{g}`")),
                _ => {}
            }
        }
        for (n, f) in now {
            if !fields.contains_key(n) {
                d.additive.push(format!("{name}: field {n} ({f}) added"));
            }
        }
    }
    for name in new
        .messages
        .keys()
        .filter(|n| !old.messages.contains_key(*n))
    {
        d.additive.push(format!("message {name} added"));
    }
    for (name, values) in &old.enums {
        let Some(now) = new.enums.get(name) else {
            d.breaking.push(format!("enum {name} removed"));
            continue;
        };
        for (n, v) in values {
            match now.get(n) {
                None => d.breaking.push(format!("{name}: value {n} ({v}) removed")),
                Some(w) if w != v => d
                    .breaking
                    .push(format!("{name}: value {n} renamed from {v} to {w}")),
                _ => {}
            }
        }
        for (n, v) in now {
            if !values.contains_key(n) {
                d.additive.push(format!("{name}: value {n} ({v}) added"));
            }
        }
    }
    for name in new.enums.keys().filter(|n| !old.enums.contains_key(*n)) {
        d.additive.push(format!("enum {name} added"));
    }
    for (name, m) in &old.methods {
        match new.methods.get(name) {
            None => d.breaking.push(format!("method {name} removed")),
            Some(n) if n != m => d
                .breaking
                .push(format!("method {name} changed from `{m}` to `{n}`")),
            _ => {}
        }
    }
    for name in new.methods.keys().filter(|n| !old.methods.contains_key(*n)) {
        d.additive.push(format!("method {name} added"));
    }
    for (topic, payload) in &old.notifications {
        match new.notifications.get(topic) {
            None => d.breaking.push(format!("notification {topic} removed")),
            Some(p) if p != payload => d.breaking.push(format!(
                "notification {topic} changed from `{payload}` to `{p}`"
            )),
            _ => {}
        }
    }
    for topic in new
        .notifications
        .keys()
        .filter(|t| !old.notifications.contains_key(*t))
    {
        d.additive.push(format!("notification {topic} added"));
    }
    d
}

/// Decide whether `new` may replace the lock `old`. Returns the problems.
pub fn check(old: &Contract, new: &Contract) -> Vec<String> {
    let (Some(ov), Some(nv)) = (old.version, new.version) else {
        return vec!["compat.lock has no version line".into()];
    };
    if nv.major > ov.major {
        return Vec::new();
    }
    if nv.major < ov.major {
        return vec![format!(
            "major version went back from {} to {}",
            ov.major, nv.major
        )];
    }
    let d = diff(old, new);
    let mut problems: Vec<String> = d
        .breaking
        .iter()
        .map(|b| format!("breaking change within major {}: {b}", nv.major))
        .collect();
    if !d.additive.is_empty() && nv.minor <= ov.minor {
        problems.push(format!(
            "additions need a minor version bump ({}.{} is already locked): {}",
            nv.major,
            ov.minor,
            d.additive.join("; ")
        ));
    }
    if d.additive.is_empty() && d.breaking.is_empty() && nv.minor < ov.minor {
        problems.push(format!(
            "minor version went back from {} to {}",
            ov.minor, nv.minor
        ));
    }
    problems
}

#[cfg(test)]
mod tests {
    use super::*;

    fn contract(text: &str) -> Contract {
        Contract::parse(text).expect("parse")
    }

    const BASE: &str = "version 1 0\nmessage A\n  1 field x u32 single\n  2 variant k.b B\n\
                        enum E\n  0 unspecified\n  1 on\nmethod s.m A -> A query\n";

    #[test]
    fn render_and_parse_round_trip() {
        let c = contract(BASE);
        assert_eq!(Contract::parse(&c.render()).expect("parse"), c);
    }

    #[test]
    fn breaking_changes_are_refused_within_a_major() {
        let old = contract(BASE);
        for (edit, expect) in [
            ("  1 field x u64 single", "changed"),
            ("  1 field y u32 single", "changed"),
            ("  1 field x u32 repeated", "changed"),
            ("", "removed"),
        ] {
            let text = BASE.replace("  1 field x u32 single\n", &format!("{edit}\n"));
            let problems = check(&old, &contract(&text.replace("\n\n", "\n")));
            assert!(
                problems.iter().any(|p| p.contains(expect)),
                "{edit:?}: {problems:?}"
            );
        }
        let renamed = contract(&BASE.replace("  1 on", "  1 enabled"));
        assert!(!check(&old, &renamed).is_empty());
        let no_method = contract(&BASE.replace("method s.m A -> A query\n", ""));
        assert!(!check(&old, &no_method).is_empty());
        let mutation = contract(&BASE.replace("query", "mutation"));
        assert!(!check(&old, &mutation).is_empty());
    }

    #[test]
    fn notifications_are_part_of_the_contract() {
        let with = format!("{BASE}notification s.pushed A\n");
        let old = contract(&with);
        assert_eq!(Contract::parse(&old.render()).expect("parse"), old);
        let removed = check(&old, &contract(BASE));
        assert!(removed.iter().any(|p| p.contains("removed")), "{removed:?}");
        let retyped = check(&old, &contract(&with.replace("s.pushed A", "s.pushed B")));
        assert!(retyped.iter().any(|p| p.contains("changed")), "{retyped:?}");
        let added = format!("{with}notification s.more A\n");
        assert!(
            !check(&old, &contract(&added)).is_empty(),
            "needs a minor bump"
        );
        let bumped = added.replace("version 1 0", "version 1 1");
        assert!(check(&old, &contract(&bumped)).is_empty());
    }

    #[test]
    fn additions_need_a_minor_bump_and_majors_may_break() {
        let old = contract(BASE);
        let added = BASE.replace("  2 variant", "  3 field z string optional\n  2 variant");
        assert!(!check(&old, &contract(&added)).is_empty());
        let bumped = added.replace("version 1 0", "version 1 1");
        assert!(check(&old, &contract(&bumped)).is_empty());
        let major = contract(
            &BASE
                .replace("version 1 0", "version 2 0")
                .replace("  1 on\n", ""),
        );
        assert!(check(&old, &major).is_empty());
    }
}
