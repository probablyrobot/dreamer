//! `cargo xtask schemes [--check]`: turn the vendored color schemes in
//! `crates/terminal-core/schemes/*.toml` into the data table
//! `crates/terminal-core/src/schemes_data.rs`. With `--check`, fail if the
//! table is not what the files produce.
//!
//! The files are alacritty-theme TOML. Only `[colors.primary]`
//! (`foreground`, `background`), `[colors.normal]`, `[colors.bright]`, and
//! the `cursor` and `background` of `[colors.cursor]` and
//! `[colors.selection]` are read; every other key is ignored.

use std::collections::BTreeMap;
use std::path::Path;

use crate::util::repo_root;

const NAMES: [&str; 8] = [
    "black", "red", "green", "yellow", "blue", "magenta", "cyan", "white",
];

/// `section -> key -> #rrggbb` for the simple TOML these files use.
fn parse(text: &str, file: &str) -> Result<BTreeMap<String, BTreeMap<String, u32>>, String> {
    let mut out: BTreeMap<String, BTreeMap<String, u32>> = BTreeMap::new();
    let mut section = String::new();
    for (n, raw) in text.lines().enumerate() {
        let line = raw.split('#').next().unwrap_or_default().trim();
        // A '#' inside a quoted color: take the line again up to a comment
        // that follows the closing quote.
        let line = if raw.contains("'#") || raw.contains("\"#") {
            raw.trim()
        } else {
            line
        };
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        if line.starts_with('[') {
            section = line.trim_matches(['[', ']']).trim().to_owned();
            continue;
        }
        let Some((key, value)) = line.split_once('=') else {
            return Err(format!("{file}:{}: not `key = value`", n + 1));
        };
        let value = value.trim();
        let quoted = value
            .strip_prefix('\'')
            .and_then(|v| v.split_once('\''))
            .or_else(|| value.strip_prefix('"').and_then(|v| v.split_once('"')))
            .map(|(v, _)| v);
        let Some(hex) = quoted.and_then(|v| v.strip_prefix('#')) else {
            continue; // keywords such as CellForeground, numbers, booleans
        };
        let color = u32::from_str_radix(hex, 16)
            .ok()
            .filter(|_| hex.len() == 6)
            .ok_or_else(|| format!("{file}:{}: `{value}` is not #rrggbb", n + 1))?;
        out.entry(section.clone())
            .or_default()
            .insert(key.trim().to_owned(), color);
    }
    Ok(out)
}

fn title(name: &str) -> String {
    name.split(['_', '-'])
        .map(|w| {
            let mut c = w.chars();
            c.next()
                .map(|f| f.to_uppercase().collect::<String>() + c.as_str())
                .unwrap_or_default()
        })
        .collect::<Vec<_>>()
        .join(" ")
}

fn dark(bg: u32) -> bool {
    let lum = |v: u32| {
        let v = f64::from(v) / 255.0;
        if v <= 0.039_28 {
            v / 12.92
        } else {
            ((v + 0.055) / 1.055).powf(2.4)
        }
    };
    let l =
        0.2126 * lum((bg >> 16) & 0xff) + 0.7152 * lum((bg >> 8) & 0xff) + 0.0722 * lum(bg & 0xff);
    // Nearer black than white in contrast terms.
    (l + 0.05) / 0.05 < 1.05 / (l + 0.05)
}

pub fn generate(root: &Path) -> Result<String, String> {
    let dir = root.join("crates/terminal-core/schemes");
    let mut files: Vec<_> = std::fs::read_dir(&dir)
        .map_err(|e| format!("{}: {e}", dir.display()))?
        .flatten()
        .map(|e| e.path())
        .filter(|p| p.extension().is_some_and(|x| x == "toml"))
        .collect();
    files.sort();
    let mut out = String::from(
        "// Generated by `cargo xtask schemes` from crates/terminal-core/schemes;\n\
         // do not edit. See schemes/SOURCES.md for where each scheme comes from.\n\n\
         use crate::schemes::{Appearance, Scheme, rgb};\n\n\
         pub(crate) const VENDORED: &[Scheme] = &[\n",
    );
    for path in files {
        let stem = path
            .file_stem()
            .map(|s| s.to_string_lossy().into_owned())
            .unwrap_or_default();
        let file = path.display().to_string();
        let text = std::fs::read_to_string(&path).map_err(|e| format!("{file}: {e}"))?;
        let t = parse(&text, &file)?;
        let get = |section: &str, key: &str| -> Option<u32> {
            t.get(&format!("colors.{section}"))?.get(key).copied()
        };
        let need = |section: &str, key: &str| -> Result<u32, String> {
            get(section, key).ok_or_else(|| format!("{file}: no colors.{section}.{key}"))
        };
        let fg = need("primary", "foreground")?;
        let bg = need("primary", "background")?;
        let mut ansi = Vec::new();
        for section in ["normal", "bright"] {
            for n in NAMES {
                ansi.push(need(section, n)?);
            }
        }
        let opt = |v: Option<u32>| v.map_or("None".to_owned(), |c| format!("Some(rgb(0x{c:06x}))"));
        let name = stem.replace('_', "-").to_ascii_lowercase();
        out.push_str(&format!(
            "    Scheme {{\n        name: {name:?},\n        title: {:?},\n        appearance: Appearance::{},\n        \
             foreground: rgb(0x{fg:06x}),\n        background: rgb(0x{bg:06x}),\n        cursor: {},\n        \
             selection: {},\n        ansi: [\n{}        ],\n    }},\n",
            title(&stem),
            if dark(bg) { "Dark" } else { "Light" },
            opt(get("cursor", "cursor")),
            opt(get("selection", "background")),
            ansi.iter()
                .map(|c| format!("            rgb(0x{c:06x}),\n"))
                .collect::<String>(),
        ));
    }
    out.push_str("];\n");
    Ok(out)
}

pub fn run(args: &[String]) -> Result<(), String> {
    let root = repo_root();
    let table = generate(&root)?;
    let path = root.join("crates/terminal-core/src/schemes_data.rs");
    if args.iter().any(|a| a == "--check") {
        let current = std::fs::read_to_string(&path).unwrap_or_default();
        if current != table {
            return Err(format!(
                "{} is stale; run `cargo xtask schemes`",
                path.display()
            ));
        }
        println!("schemes: up to date");
        return Ok(());
    }
    std::fs::write(&path, table).map_err(|e| format!("{}: {e}", path.display()))?;
    println!("schemes: wrote {}", path.display());
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn colors_are_read_from_sections_and_comments_and_keywords_are_skipped() {
        let t = parse(
            "[colors.primary]\nbackground = '#1E1E2E' # base\nforeground = \"#cdd6f4\"\n\
             [colors.selection]\ntext = 'CellForeground'\n",
            "x",
        )
        .expect("parse");
        assert_eq!(t["colors.primary"]["background"], 0x1e1e2e);
        assert_eq!(t["colors.primary"]["foreground"], 0xcdd6f4);
        assert!(!t.contains_key("colors.selection"));
        assert!(parse("[a]\nx = '#12345'\n", "x").is_err());
        assert_eq!(title("tokyo_night_storm"), "Tokyo Night Storm");
        assert!(dark(0x1e1e2e) && !dark(0xeff1f5));
    }
}
